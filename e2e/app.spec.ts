import { expect, test, type Page } from '@playwright/test';

/**
 * End-to-end coverage of the acceptance checklist.
 *
 * Every assertion here runs against the real production build in a real
 * browser: no mocks, no stubbed storage, no fabricated results.
 */

const BASE = '/digital-dna/';

async function completeWizard(page: Page, nickname = 'E2E Helix') {
  await page.goto(`${BASE}#/create`);
  await expect(page.getByRole('heading', { name: /Identity/i }).first()).toBeVisible();

  // Step 1 — identity
  await page.getByLabel(/Nickname/i).fill(nickname);
  await page.getByLabel(/Short bio/i).fill('Generated by the end-to-end test.');
  await page.getByRole('button', { name: /Continue/i }).click();

  // Step 2 — interests
  await expect(page.getByText(/Pick your domains/i).first()).toBeVisible();
  await page.getByRole('button', { name: 'AI', exact: true }).click();
  await page.getByRole('button', { name: 'Design', exact: true }).click();
  await page.getByRole('button', { name: /Continue/i }).click();

  // Step 3 — skills
  await expect(page.getByText(/What can you do/i).first()).toBeVisible();
  await page.getByRole('button', { name: 'Programming', exact: true }).click();
  await page.getByRole('button', { name: /Continue/i }).click();

  // Step 4 — creative
  await expect(page.getByText(/What do you most like to make/i).first()).toBeVisible();
  await page.getByRole('button', { name: /Systems/i }).first().click();
  await page.getByRole('button', { name: /Continue/i }).click();

  // Step 5 — habits
  await expect(page.getByText(/Platforms you spend time on/i).first()).toBeVisible();
  await page.getByRole('button', { name: 'GitHub', exact: true }).click();
  await page.getByRole('button', { name: /Continue/i }).click();

  // Step 6 — visual
  await expect(page.getByText(/Pick the aesthetic/i).first()).toBeVisible();
  await page.getByRole('button', { name: /Cyberpunk/i }).first().click();
  await page.getByRole('button', { name: /Continue/i }).click();

  // Step 7 — review
  await expect(page.getByText(/Ready/i).first()).toBeVisible();
  await page.getByRole('button', { name: /Generate my DNA/i }).click();
}

test.describe('public site', () => {
  test('landing page states the product promise and links the author', async ({ page }) => {
    await page.goto(BASE);
    await expect(page.getByRole('heading', { level: 1 })).toContainText('Your Digital DNA');
    await expect(page.getByRole('link', { name: /Create My DNA/i }).first()).toBeVisible();

    // Author X link is present in the header and points at the right profile.
    const headerLink = page.locator('header a[href="https://x.com/0xkillcoin"]').first();
    await expect(headerLink).toBeVisible();
    await expect(headerLink).toHaveAttribute('href', 'https://x.com/0xkillcoin');
    await expect(headerLink).toHaveAttribute('target', '_blank');
  });

  test('shows the real helix renderer on the landing page', async ({ page }) => {
    await page.goto(BASE);
    const svgs = page.locator('main svg[role="img"]');
    await expect(svgs.first()).toBeVisible();
    // The hero helix must be drawn from real path data (hundreds of Bézier
    // segments), not a placeholder image or an empty element.
    const strand = page.locator('main svg[role="img"] path[data-part="strand-a"]').first();
    const d = await strand.getAttribute('d');
    expect(d).toBeTruthy();
    expect(d!.split('C').length).toBeGreaterThan(50);
    // Several independent live renders, and no raster stand-in for artwork.
    expect(await page.locator('main svg[role="img"]').count()).toBeGreaterThan(2);
    expect(await page.locator('main img:not([alt=""])').count()).toBe(0);
  });
});

test.describe('creation flow', () => {
  test('creates a DNA, persists it across a reload, and renders every chart', async ({ page }) => {
    await completeWizard(page);

    // Generation screen then the result page.
    await expect(page.getByText(/Sequencing/i).first()).toBeVisible({ timeout: 15_000 });
    await expect(page.getByText(/^DNA-[0-9A-F]{6}$/).first()).toBeVisible({ timeout: 20_000 });

    const codeBefore = (await page.getByText(/^DNA-[0-9A-F]{6}$/).first().innerText()).trim();
    expect(codeBefore).toMatch(/^DNA-[0-9A-F]{6}$/);

    // All the data visualisations are present as real SVG, not images.
    await expect(page.getByRole('img', { name: /helix/i }).first()).toBeVisible();
    expect(await page.locator('main svg').count()).toBeGreaterThan(3);

    // Reload: data must survive (IndexedDB persistence).
    await page.reload();
    await page.goto(`${BASE}#/dna`);
    await expect(page.getByText(codeBefore).first()).toBeVisible({ timeout: 15_000 });
  });

  test('wizard blocks progress until the step is valid', async ({ page }) => {
    await page.goto(`${BASE}#/create`);
    const continueBtn = page.getByRole('button', { name: /Continue/i });
    await expect(continueBtn).toBeDisabled();
    await page.getByLabel(/Nickname/i).fill('Blocked Test');
    await expect(continueBtn).toBeEnabled();
  });

  test('goes back and keeps earlier answers', async ({ page }) => {
    await page.goto(`${BASE}#/create`);
    await page.getByLabel(/Nickname/i).fill('Back Nav');
    await page.getByRole('button', { name: /Continue/i }).click();
    await page.getByRole('button', { name: 'AI', exact: true }).click();
    await page.getByRole('button', { name: /Back/i }).click();
    await expect(page.getByLabel(/Nickname/i)).toHaveValue('Back Nav');
  });
});

test.describe('deterministic engine', () => {
  test('identical answers produce an identical DNA number', async ({ page }) => {
    await completeWizard(page, 'Determinism Check');
    await expect(page.getByText(/^DNA-[0-9A-F]{6}$/).first()).toBeVisible({ timeout: 20_000 });
    const first = (await page.getByText(/^DNA-[0-9A-F]{6}$/).first().innerText()).trim();

    // Delete everything, then answer the exact same way again.
    await page.goto(`${BASE}#/settings`);
    await page.getByRole('button', { name: /Delete my data/i }).click();
    await page.getByRole('button', { name: /Yes, delete everything/i }).click();
    // The app navigates home once the delete has actually completed, so wait for
    // that landing URL instead of the settings URL we started from.
    await expect(page.getByRole('heading', { level: 1 })).toContainText('Your Digital DNA', { timeout: 20_000 });

    await completeWizard(page, 'Determinism Check');
    await expect(page.getByText(/^DNA-[0-9A-F]{6}$/).first()).toBeVisible({ timeout: 20_000 });
    const second = (await page.getByText(/^DNA-[0-9A-F]{6}$/).first().innerText()).trim();

    expect(second).toBe(first);
  });
});

test.describe('share and export', () => {
  test('exports a PNG and produces a working public link', async ({ page, context }) => {
    await completeWizard(page, 'Share Tester');
    await expect(page.getByText(/^DNA-[0-9A-F]{6}$/).first()).toBeVisible({ timeout: 20_000 });

    // Switch to public: a real link must appear in a readable, selectable field
    // (this is what makes sharing work even where the clipboard API is blocked).
    await page.getByRole('button', { name: /^Public$/ }).click();
    const linkField = page.getByLabel('Public share link');
    await expect(linkField).toBeVisible();
    const url = await linkField.inputValue();
    expect(url).toContain('#/dna/');
    expect(url.length).toBeGreaterThan(60);

    // The copy button must at least acknowledge the action without throwing.
    await page.getByRole('button', { name: /Copy public link/i }).click();

    // Open the share link in a fresh page: it must render with no local storage.
    const fresh = await context.newPage();
    await fresh.goto(url);
    await expect(fresh.getByText(/Shared view/i)).toBeVisible({ timeout: 15_000 });
    await expect(fresh.getByText(/^DNA-[0-9A-F]{6}$/).first()).toBeVisible();
    await fresh.close();

    // PNG export actually produces a file.
    const download = page.waitForEvent('download', { timeout: 45_000 });
    await page.getByRole('button', { name: /Square card/i }).click();
    const file = await download;
    expect(file.suggestedFilename()).toMatch(/-square\.png$/);
  });

  test('private mode produces no share link', async ({ page }) => {
    await completeWizard(page, 'Private Only');
    await expect(page.getByText(/^DNA-[0-9A-F]{6}$/).first()).toBeVisible({ timeout: 20_000 });
    await page.getByRole('button', { name: /^Private$/ }).click();
    await expect(page.getByRole('button', { name: /Copy public link/i })).toHaveCount(0);
    await expect(page.getByText(/no share link is produced/i)).toBeVisible();
  });
});

