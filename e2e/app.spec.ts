test.describe('data portability', () => {
  test('exports JSON and re-imports it', async ({ page }) => {
    await completeWizard(page, 'Backup Tester');
    await expect(page.getByText(/^DNA-[0-9A-F]{6}$/).first()).toBeVisible({ timeout: 20_000 });
    const code = (await page.getByText(/^DNA-[0-9A-F]{6}$/).first().innerText()).trim();

    await page.goto(`${BASE}#/settings`);
    const download = page.waitForEvent('download');
    await page.getByRole('button', { name: /Export JSON/i }).click();
    const file = await download;
    const path = await file.path();
    expect(path).toBeTruthy();

    await page.getByRole('button', { name: /Delete my data/i }).click();
    await page.getByRole('button', { name: /Yes, delete everything/i }).click();
    await page.waitForURL(/#\/$/);

    await page.goto(`${BASE}#/settings`);
    await page.setInputFiles('input[type="file"][accept*="json"]', path!);
    await expect(page.getByText(/Imported 1 profile/i)).toBeVisible({ timeout: 15_000 });

    await page.goto(`${BASE}#/dna`);
    await expect(page.getByText(code).first()).toBeVisible({ timeout: 15_000 });
  });
});

